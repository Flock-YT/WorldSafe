#!/usr/bin/env python3
"""Exercise one immutable universal JAR across the locked game/environment matrix."""

import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jar", type=Path, required=True)
    parser.add_argument("--java-homes", type=Path, required=True,
                        help='JSON object mapping Java majors to JAVA_HOME; optional "client-8"/"client-17" overrides')
    parser.add_argument("--targets", help="Explicit locked subset for development; default is all releases")
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--environments", choices=("both", "dedicated", "integrated"), default="both")
    parser.add_argument("--smoke", action="store_true", help="Development only: permit explicitly incomplete feature coverage")
    parser.add_argument("--accept-eula", action="store_true")
    args = parser.parse_args()
    if not args.accept_eula:
        parser.error("Minecraft EULA acceptance is required via --accept-eula")
    if args.jobs < 1 or args.jobs > 8:
        parser.error("--jobs must be between 1 and 8")
    lock = json.loads((ROOT / "fabric/versions.lock.json").read_text())
    known = {item["minecraft"]: item for item in lock["targets"]}
    games = args.targets.split(",") if args.targets else list(known)
    if len(set(games)) != len(games) or any(game not in known for game in games):
        parser.error("Targets must be distinct versions from the lock")
    homes = json.loads(args.java_homes.read_text())
    jar = args.jar.resolve()
    digest = hashlib.sha256(jar.read_bytes()).hexdigest()
    reports = ROOT / "fabric/build/architecture-reports" / lock["loader"]
    logs = ROOT / "fabric/build/matrix-logs" / lock["loader"]
    logs.mkdir(parents=True, exist_ok=True)

    def run(game):
        java = str(known[game]["java"])
        driver_dir = ROOT / "fabric/build/targets" / ("driver_mc" + game.replace(".", "_")) / "build/libs"
        candidates = [p for p in driver_dir.glob("*.jar") if not any(s in p.name for s in ("-dev", "-sources"))]
        # Old dev artifacts from an earlier archive base name are not authoritative.
        candidates.sort(key=lambda p: (not p.name.startswith("WorldSafe-Architecture-Driver-"), -p.stat().st_mtime))
        result = {"minecraft": game, "environments": {}}
        if not candidates:
            result["error"] = "Matching external test driver was not built"
            return result
        for environment in ("server", "client"):
            if environment == "client" and args.environments == "dedicated":
                continue
            # Integrated probes use a vanilla saved world generated by the dedicated probe.
            home = homes.get("client-" + java, homes[java]) if environment == "client" else homes[java]
            command = [sys.executable, str(ROOT / "scripts" / ("run-fabric-architecture-probe.py" if environment == "server"
                       else "run-fabric-client-architecture-probe.py")), "--game", game, "--jar", str(jar),
                       "--java-home", home, "--driver", str(candidates[0]), "--behavior"]
            if environment == "server":
                command.append("--accept-eula")
            elif platform.system() == "Darwin" and "x64" in home:
                command.extend(("--architecture", "x86_64"))
            report_file = reports / (game + "-" + environment + ".json")
            report_file.unlink(missing_ok=True)
            with (logs / (game + "-" + environment + ".log")).open("w") as output:
                completed = subprocess.run(command, cwd=ROOT, stdout=output, stderr=subprocess.STDOUT)
            report = json.loads(report_file.read_text()) if report_file.is_file() else {"error": "Missing report"}
            valid = (completed.returncode == 0 and report.get("passed", False)
                     and report.get("jarSha256") == digest and report.get("loader") == lock["loader"])
            if not args.smoke:
                valid &= report.get("fullCoverageComplete", False)
            report["matrixPassed"] = bool(valid)
            behavior_file = Path(report.get("behaviorReport", ""))
            if behavior_file.is_file():
                report["behavior"] = json.loads(behavior_file.read_text())
            result["environments"][environment] = report
            print(game, environment, "PASS" if valid else "FAIL", flush=True)
        return result

    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = list(pool.map(run, games))
    unchanged = hashlib.sha256(jar.read_bytes()).hexdigest() == digest
    required = {"server", "client"} if args.environments == "both" else {"server"} if args.environments == "dedicated" else {"client"}
    passed = unchanged and all(not item.get("error") and required.issubset(item["environments"])
                              and all(item["environments"][env].get("matrixPassed") for env in required) for item in results)
    report = {"jarSha256": digest, "loader": lock["loader"], "artifactUnchanged": unchanged, "targets": games,
              "developmentSmokeOnly": args.smoke, "passed": passed,
              "complete": passed and not args.smoke and set(games) == set(known) and args.environments == "both",
              "results": results}
    destination = ROOT / "fabric/build/matrix-report.json"
    destination.write_text(json.dumps(report, indent=2) + "\n")
    print("Matrix report:", destination, "complete=" + str(report["complete"]), flush=True)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
